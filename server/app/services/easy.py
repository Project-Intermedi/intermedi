# 토큰 끝에 붙은 동작어 — 떼고 질환명만 남긴다
ACT = ('의 치료', '치료', '의 예방', '예방', '의 완화', '완화', '의 개선', '개선',
       '억제', '방지', '보조', '요법', '투여')
BAD = ('환자', '유효균종', '적응증', '경우', '다음', '이상', '사용', '후유증', '기타',
       '소염', '진통', '증상의', '투여', '처치', '수술전')
PAREN = re.compile(r'\([^)]*\)|\[[^\]]*\]')
GERM = re.compile(r'○?\s*유효균종.*?(?=○|■|\Z)', re.S)
SPLIT = re.compile(r'[,·/:;\u2024\u00b7ㆍ]|\s및\s|\s또는\s|\n')
LEAD = re.compile(r'^[\s■○\-–ㆍ·]*(?:\d+\s*[.)])?\s*')


def jong(w):
    c = w.strip()[-1] if w.strip() else ''
    return '가' <= c <= '힣' and (ord(c) - 0xAC00) % 28 != 0


def head_of(atc):
    a = (atc or '').strip()
    return (ATC4.get(a[:4]) or ATC2.get(a[:3]) or ATC1.get(a[:1]))


def diseases(eff, k=3):
    s = GERM.sub(' ', eff or '')
    s = PAREN.sub(' ', s)
    out = []
    for t in SPLIT.split(s):
        t = LEAD.sub('', t).strip().strip('.。:')
        for a in ACT:
            if t.endswith(a):
                t = t[: -len(a)].strip()
                break
        if not (2 <= len(t) <= 16):
            continue
        if any(b in t for b in BAD):
            continue
        if t.endswith('군'):
            t = t[:-1]
        if not t.endswith(TAIL):
            continue
        if any(t in o or o in t for o in out):
            continue
        out.append(t)
        if len(out) >= k:
            break
    return out


def summary(atc, eff):
    parts = []
    h = head_of(atc)
    if h:
        parts.append(f'{h}{"이에요" if jong(h) else "예요"}.')
    d = diseases(eff)
    if d:
        parts.append(f'{", ".join(d)} 등에 사용해요.')
    return ' '.join(parts)
