def plain(reason: str) -> str:
    """금기 사유 원문 → 쉬운 말 한 문장"""
    s = (reason or '').strip().lower()
    if not s:
        return DEFAULT

    for keys, text in RULES:
        if any(k in s for k in keys):
            return text

    if '농도' in s or '노출' in s or '독성' in s or '작용' in s:
        if any(d in s for d in DOWN):
            return LESS
        if any(u in s for u in UP):
            return MORE
    if any(d in s for d in DOWN):
        return LESS
    return DEFAULT


# ── 연령 추출 ────────────────────────────────────────
AGE_NUM = re.compile(r'(\d+)\s*(세|개월|주)\s*(미만|이하|이상|초과|까지)')
AGE_WORD = ('신생아', '미숙아', '영아', '유아', '소아', '청소년', '어린이')


def age_of(detail: str) -> str:
    """금기 사유에서 연령 표현 뽑기 — 못 찾으면 빈 문자열"""
    s = detail or ''
    hits = AGE_NUM.findall(s)
    if hits:
        # '1세 이상 7세 미만' 처럼 둘이 짝이면 같이 보여준다
        return ' '.join(f'{n}{u} {"이하" if c == "까지" else c}'
                        for n, u, c in hits[:2])
    for w in AGE_WORD:
        if w in s:
            return w
    return ''


def _eun(word):
    """받침 보고 은/는 고르기"""
    last = word[-1]
    if '가' <= last <= '힣':
        return '은' if (ord(last) - 0xAC00) % 28 else '는'
    return '은(는)'


def age_guide(notes) -> str:
    """나온 연령은 다 안내한다 — 빈 것만 뺀다"""
    uniq = sorted({n for n in notes if n})
    if not uniq:
        return GUIDE['특정연령대금기']

    text = ' · '.join(uniq[:3])
    if len(uniq) > 3:
        text += ' 등'
    return f'{text}{_eun(text)} 복용하지 않도록 주의해요.'